"""Builds review_flavours.md and V13__flavoured_bank.sql from bank_flavours.py (sde-focus tickets 09 to 11).

Run from this folder:  python gen_flavours.py
The questions are general knowledge written by Claude and have NOT been reviewed. Check review_flavours.md, fix bank_flavours.py, run again,
then move V13__flavoured_bank.sql to ../migration/ (V12 adds the format and track columns it needs). A row loaded with source 'seed' counts as reviewed.
"""
import hashlib, json, sys
from pathlib import Path
from bank_common import BLANK
from bank_flavours import ROWS

HERE = Path(__file__).parent
LEVELS = ["easy", "medium", "hard"]


def hash_text(target, kind, text):
    """Same recipe as gen_bank.py: SHA-256 of skill|type|text, stripped and lower-cased."""
    return hashlib.sha256(f"{target}|{kind}|{text}".strip().lower().encode("utf-8")).hexdigest()


def sql(s):
    return "NULL" if s is None else "'" + s.replace("'", "''") + "'"


def check(row):
    skill, kind, fmt, track, level, text, extra = row
    where = f"{skill}: {text[:50]}"
    assert level in LEVELS and fmt in ("standard", "design", "code") and track in ("backend", "frontend"), where
    strings = [text]
    if kind == "multiple_correct":
        options, correct = extra
        assert len(options) == 4 and len(set(options)) == 4, f"need 4 different options: {where}"
        assert correct and set(correct) <= set("ABCD") and len(set(correct)) == len(correct) < 4, f"1 to 3 correct letters: {where}"
        strings += options
    elif kind == "fill_blank":
        assert text.count(BLANK) == len(extra) and all(extra), f"blanks and accepted wordings differ: {where}"
        strings += [w for a in extra for w in a]
    else:
        facts, keywords = extra
        want = {"design": (5, 6), "code": (5, 5), "standard": (3, 3)}[fmt]
        assert want[0] <= len(facts) <= want[1] and len(set(facts)) == len(facts) and all(len(f) <= 500 for f in facts), f"key facts: {where}"
        assert keywords, f"keywords: {where}"
        assert (fmt == "design") == (kind == "voice"), f"design is the only voice format: {where}"
        strings += facts + keywords
    for s in strings:
        assert s.strip() and '"' not in s and "\\" not in s, f"avoid empty strings, double quotes and backslashes: {s[:60]}"


def main():
    hashes = set()
    for r in ROWS:
        check(r)
        h = hash_text(r[0], r[1], r[5])
        assert h not in hashes, f"duplicate question: {r[5][:60]}"
        hashes.add(h)

    cols = ("INSERT INTO bank_question (type, skill_id, theme, difficulty, text_template, options, correct_options, accepted_answers, key_facts, keywords, source, text_hash, format, track)")
    lines = ["-- V13: role-flavoured practice bank (sde-focus tickets 09 to 11): design, SQL and endpoint, and frontend questions.",
             "-- Generated by gen_flavours.py. General knowledge, to be reviewed by the owner before this file is moved to db/migration/.",
             "-- Rows are shared by all users, marked 'seed' (reviewed) once loaded, and hold no personal data.", ""]
    md = ["# Role-flavoured bank review (design, SQL and endpoint, frontend)", "",
          "Check every question. Correct options are **bold**. Fix it in `bank_flavours.py`, run `python gen_flavours.py` again,",
          "then move `V13__flavoured_bank.sql` to `db/migration/` (after `V12`).", ""]
    last = None
    for skill, kind, fmt, track, level, text, extra in ROWS:
        options = correct = accepted = facts = keywords = None
        if kind == "multiple_correct":
            options = json.dumps([{"key": k, "text": t} for k, t in zip("ABCD", extra[0])], ensure_ascii=False)
            correct = json.dumps(list(extra[1]))
        elif kind == "fill_blank":
            accepted = json.dumps(extra, ensure_ascii=False)
        else:
            facts, keywords = json.dumps(extra[0], ensure_ascii=False), json.dumps(extra[1], ensure_ascii=False)
        lines.append(f"{cols}\nSELECT {sql(kind)}, id, NULL, {sql(level)}, {sql(text)}, {sql(options)}, {sql(correct)}, {sql(accepted)}, {sql(facts)}, {sql(keywords)}, "
                     f"'seed', {sql(hash_text(skill, kind, text))}, {sql(fmt)}, {sql(track)}\nFROM skill WHERE name = {sql(skill)};")
        head = f"## {track.title()} / {fmt}: {skill}"
        if head != last:
            md += [head, ""]
            last = head
        label = {"multiple_correct": "MC", "fill_blank": "Blank", "brief": "Brief", "voice": "Design"}[kind]
        md.append(f"- [ ] **{label}, {level}:** " + text.replace("\n", "\n  "))
        if kind == "multiple_correct":
            md += [f"  - {k}. " + (f"**{t}**" if k in extra[1] else t) for k, t in zip("ABCD", extra[0])]
        elif kind == "fill_blank":
            md.append("  Accepted: " + " / ".join(", ".join(a) for a in extra))
        else:
            md += [f"  - Key fact: {f}" for f in extra[0]]
        md.append("")
    (HERE / "V13__flavoured_bank.sql").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (HERE / "review_flavours.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    from collections import Counter
    print(len(ROWS), "rows:", dict(Counter((r[3], r[2], r[1]) for r in ROWS)))


if __name__ == "__main__":
    sys.exit(main())
